@router.post("/formula/upload-lookup")
async def upload_lookup_table(session_id: str, file: UploadFile = File(...)):
    _get_df_or_404(session_id)  # 404s early if the main session doesn't exist
    content = await file.read()
    if not content:
        raise HTTPException(400, "Lookup file khali hai.")
    try:
        lookup_df = excel_io.read_upload(file.filename, content)
    except Exception as e:  # noqa: BLE001
        raise HTTPException(400, f"Lookup file padhne mein error: {e}")
    if lookup_df.empty:
        raise HTTPException(400, "Lookup file mein koi data nahi mila.")

    sessions.set_lookup_df(session_id, lookup_df, filename=file.filename)
    return {"status": "lookup_uploaded", "filename": file.filename, **excel_io.df_preview(lookup_df)}


@router.get("/formula/lookup-preview/{session_id}")
def lookup_preview(session_id: str):
    try:
        lookup_df = sessions.get_lookup_df(session_id)
    except sessions.SessionNotFound:
        raise HTTPException(404, "Session nahi mila — file dobara upload karo.")
    except sessions.LookupNotFound:
        raise HTTPException(404, "Abhi tak koi lookup table upload nahi hui.")
    return excel_io.df_preview(lookup_df)


def _run_lookup(payload: LookupRequest):
    df = _get_df_or_404(payload.session_id)
    try:
        lookup_df = sessions.get_lookup_df(payload.session_id)
    except sessions.LookupNotFound:
        raise HTTPException(400, "Pehle POST /api/formula/upload-lookup se lookup table upload karo.")
    try:
        new_df, explanation = excel_formulas.vlookup(
            df, lookup_df, payload.key_column, payload.lookup_key_column, payload.value_columns, payload.how,
        )
    except ValueError as e:
        raise HTTPException(400, str(e))
    sessions.update_working_df(payload.session_id, new_df, instruction="[lookup]", explanation=explanation)
    return {"explanation": explanation, **excel_io.df_preview(new_df)}


@router.post("/formula/vlookup")
def formula_vlookup(payload: LookupRequest):
    return _run_lookup(payload)


@router.post("/formula/index-match")
def formula_index_match(payload: LookupRequest):
    # Same underlying merge as VLOOKUP — see excel_formulas.vlookup's docstring
    # for why INDEX/MATCH's "look in either direction" advantage doesn't
    # apply once you're joining dataframes instead of reading an Excel range.
    return _run_lookup(payload)


