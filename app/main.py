# --------------------------------------------------------------------------- #
# Request/response models
# --------------------------------------------------------------------------- #

class DedupeRequest(BaseModel):
    session_id: str
    columns: Optional[List[str]] = None
    threshold: int = 87


class QuickFixRequest(BaseModel):
    session_id: str
    problem: str = ""            # free-text problem description, matched by keyword
    fix_id: Optional[str] = None  # or skip matching and pick a fix directly (from the chip list)


class ApplyDedupeRequest(BaseModel):
    session_id: str
    drop_indices: List[int]


class AnomalyRequest(BaseModel):
    session_id: str
    column: str
    threshold: float = 3.5


class DropRowsRequest(BaseModel):
    session_id: str
    row_indices: List[int]


class MissingValuesRequest(BaseModel):
    session_id: str


class FillMissingRequest(BaseModel):
    session_id: str
    # {"column_name": {"method": "mean"|"median"|"mode"|"constant"|"ffill"|"bfill"|"drop_rows", "value": <for constant>}}
    strategies: Dict[str, Dict[str, Any]]


class SessionIdRequest(BaseModel):
    session_id: str


class LookupRequest(BaseModel):
    session_id: str
    key_column: str
    lookup_key_column: str
    value_columns: List[str]
    how: str = "left"


class HLookupRequest(BaseModel):
    session_id: str
    key_column: str
    lookup_key_row_index: int
    value_row_index: int


class PivotRequest(BaseModel):
    session_id: str
    index_cols: List[str]
    values_col: str
    agg_func: str = "sum"
    columns_col: Optional[str] = None
    replace_working: bool = False  # if True, pivot result becomes the new working sheet


class IfFormulaRequest(BaseModel):
    session_id: str
    column: str
    op: str
    value: Any
    true_value: Any
    false_value: Any
    new_column: str


class AggregateRequest(BaseModel):
    session_id: str
    column: str
    func: str
    condition_column: Optional[str] = None
    condition_op: Optional[str] = None
    condition_value: Optional[Any] = None


class ConcatenateRequest(BaseModel):
    session_id: str
    columns: List[str]
    separator: str = " "
    new_column: str


class TextExtractRequest(BaseModel):
    session_id: str
    column: str
    mode: str  # left | right | mid | len
    new_column: str
    n: Optional[int] = None
    start: Optional[int] = None
    length: Optional[int] = None


class SerialNumberRequest(BaseModel):
    session_id: str
    new_column: str = "Sr No"
    start: int = 1


class RankRequest(BaseModel):
    session_id: str
    column: str
    new_column: str
    ascending: bool = False


class UniqueRequest(BaseModel):
    session_id: str
    column: str


