"""
SheetVaidya backend — FastAPI + pandas, Redis-backed sessions (works on
serverless hosts like Vercel, where every request can hit a different,
stateless function instance).

Rule-based/statistical cleanup only — no AI/LLM calls anywhere in this
backend. Cleanup happens via explicit, pre-written pandas "formulas"
(fuzzy dedupe, MAD anomaly detection, missing-value fill, and a small
registry of built-in quick fixes matched by keyword) — nothing is
generated by a model.

Run locally:
    uvicorn app.main:app --reload

Env:
    REDIS_URL          required for session storage (Vercel KV / Upstash /
                        any Redis-protocol store). KV_URL also works.

Endpoints (all under /api — this lets the same Vercel deployment also
serve the static frontend at the site root, see vercel.json):
    GET  /api                        -> friendly landing JSON (see /docs)
    GET  /api/health                 -> liveness check
    POST /api/upload                 -> upload a file, get session_id + preview
    GET  /api/preview/{session_id}   -> current working-data preview
    POST /api/reset                  -> undo all fixes, back to original upload
    GET  /api/quick-fixes            -> list of built-in fixes (id + label)
    POST /api/quick-fix              -> describe a problem (or pass fix_id) -> built-in fix applied
    POST /api/smart-duplicates       -> find fuzzy/near-duplicate row groups
    POST /api/apply-dedupe           -> drop chosen duplicate rows
    POST /api/detect-anomalies       -> flag outlier values in a numeric column
    POST /api/drop-rows              -> drop arbitrary row indices (e.g. anomalies)
    POST /api/missing-values         -> per-column missing-value report + suggested fill
    POST /api/fill-missing           -> apply a fill strategy per column
    GET  /api/quality-report/{id}    -> overall data-quality score (0-100) + issue list
    POST /api/undo                   -> step back one change (multi-step, not just reset)
    POST /api/redo                   -> re-apply a change that was undone
    GET  /api/history/{session_id}   -> fix history + can_undo/can_redo flags
    GET  /api/download/{session_id}  -> download as .xlsx / .csv / .pdf (?format=)

    -- Excel-formula-equivalents (app/excel_formulas.py) --
    POST /api/formula/upload-lookup    -> upload a second table for VLOOKUP/HLOOKUP
    POST /api/formula/vlookup          -> VLOOKUP-style merge from the lookup table
    POST /api/formula/index-match      -> same as vlookup (INDEX/MATCH == VLOOKUP for a merge)
    POST /api/formula/hlookup          -> HLOOKUP-style merge (lookup table keyed by row)
    POST /api/formula/pivot            -> pivot table (rows/columns/values/aggfunc)
    POST /api/formula/if                -> IF-style conditional column
    POST /api/formula/aggregate        -> SUM/AVERAGE/COUNT/COUNTIF/SUMIF/... on a column
    POST /api/formula/concatenate      -> CONCATENATE-style column join
    POST /api/formula/text-extract     -> LEFT / RIGHT / MID / LEN
    POST /api/formula/serial-number    -> add a running Sr. No. column
    POST /api/formula/rank             -> RANK-style column
    POST /api/formula/unique           -> UNIQUE-style distinct value list (read-only)
"""

from typing import Any, Dict, List, Optional

from fastapi import APIRouter, FastAPI, File, HTTPException, UploadFile
