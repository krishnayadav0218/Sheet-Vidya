@router.get("/quick-fixes")
def quick_fixes_list():
    return {"fixes": builtin_fixes.list_fixes()}


@router.post("/quick-fix")
def quick_fix(payload: QuickFixRequest):
    df = _get_df_or_404(payload.session_id)

    if payload.fix_id:
        result = builtin_fixes.apply_fix_by_id(df, payload.fix_id)
        if result is None:
            raise HTTPException(400, "Ye fix_id nahi mila. GET /api/quick-fixes se list dekho.")
        matched_label = payload.fix_id
        fix_id = payload.fix_id
    else:
        if not payload.problem.strip():
            raise HTTPException(400, "Problem likho ya ek built-in fix chuno.")
        matched = builtin_fixes.match_fix(payload.problem)
        if not matched:
            available = ", ".join(f["label"] for f in builtin_fixes.list_fixes())
            raise HTTPException(
                404,
                f"Koi built-in fix match nahi hua. Available fixes: {available}",
            )
        result = matched["fn"](df)
        matched_label = matched["label"]
        fix_id = matched["id"]

    new_df, explanation = result
    sessions.update_working_df(
        payload.session_id, new_df,
        instruction=payload.problem or matched_label,
        explanation=explanation,
    )
    sessions.log_recipe_step(payload.session_id, "quick_fix", {"fix_id": fix_id})
    return {"matched_fix": matched_label, "explanation": explanation, **excel_io.df_preview(new_df)}


