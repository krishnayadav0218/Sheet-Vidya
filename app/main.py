@router.post("/upload")
async def upload(request: Request, file: UploadFile = File(...)):
    client_ip = request.client.host if request.client else "unknown"
    if not sessions.check_rate_limit("upload", client_ip, max_requests=20, window_seconds=60):
        log.warning("rate_limit_hit", extra={"bucket": "upload", "client_ip": client_ip})
        raise HTTPException(429, "Bahut zyada uploads ho gaye — thodi der baad try karo (max 20/minute).")

    content = await file.read()
    if not content:
        raise HTTPException(400, "File khali hai.")

    try:
        sheets, active_sheet = excel_io.read_upload_all_sheets(file.filename, content)
    except Exception as e:  # noqa: BLE001
        log.warning("upload_parse_failed", extra={"upload_filename": file.filename, "error": str(e)})
        raise HTTPException(400, f"File padhne mein error: {e}")

    df = sheets[active_sheet]
    if df.empty:
        raise HTTPException(400, "Is file mein koi data nahi mila.")

    try:
        session_id = sessions.create(file.filename, df, sheets=sheets, active_sheet=active_sheet)
    except RuntimeError as e:
        log.error("session_create_failed", extra={"error": str(e)})
        raise HTTPException(500, str(e))

    log.info("upload_success", extra={
        "session_id": session_id, "upload_filename": file.filename,
        "rows": len(df), "sheet_count": len(sheets),
    })
    return {
        "session_id": session_id, "filename": file.filename,
        "available_sheets": list(sheets.keys()), "active_sheet": active_sheet,
        **excel_io.df_preview(df),
    }


