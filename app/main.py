@app.exception_handler(Exception)
async def unhandled_exception_handler(request: Request, exc: Exception):
    """Safety net: any exception not already an HTTPException (e.g. an
    unexpected bug, or Redis being unreachable somewhere we didn't
    anticipate) still gets a clean JSON response instead of an HTML error
    page — which is exactly what broke the frontend's res.json() calls
    before this was added (see the rate-limit fail-open fix in
    session_store.check_rate_limit for the specific bug that motivated
    this). The frontend can always safely call res.json() on any response.
    """
    log.error("unhandled_exception", extra={"path": str(request.url.path), "error": str(exc)})
    return JSONResponse(status_code=500, content={"detail": f"Server error: {exc}"})


