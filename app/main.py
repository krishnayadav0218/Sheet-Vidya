@router.post("/formula/upload-lookup")
async def upload_lookup_table(request: Request, session_id: str, file: UploadFile = File(...)):
    _get_df_or_404(session_id)  # 404s early if the main session doesn't exist
    client_ip = request.client.host if request.client else "unknown"
    if not sessions.check_rate_limit("upload", client_ip, max_requests=20, window_seconds=60):
        raise HTTPException(429, "Bahut zyada uploads ho gaye — thodi der baad try karo (max 20/minute).")

    content = await file.read()
    if not content:
        raise HTTPException(400, "Lookup file khali hai.")
    try:
        lookup_df = excel_io.read_upload(file.filename, content)
    except Exception as e:  # noqa: BLE001
        raise HTTPException(400, f"Lookup file padhne mein error: {e}")
    if lookup_df.empty:
        raise HTTPException(400, "Lookup file mein koi data nahi mila.")

    sessions.set_lookup_df(session_id, lookup_df, filename=file.filename)
    return {"status": "lookup_uploaded", "filename": file.filename, **excel_io.df_preview(lookup_df)}


