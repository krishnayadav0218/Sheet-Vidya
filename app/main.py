@router.get("/recipes/{name}")
def get_recipe(name: str):
    try:
        recipe = sessions.get_recipe(name)
    except sessions.RecipeNotFound:
        raise HTTPException(404, f"Recipe '{name}' nahi mili.")
    steps_with_labels = [
        {**step, "label": recipes.ACTION_LABELS.get(step.get("action"), step.get("action"))}
        for step in recipe["steps"]
    ]
    return {"name": recipe["name"], "steps": steps_with_labels, "created_at": recipe["created_at"]}


